"""Keep dependency versions while moving matching lock entries to new homes.

Cargo must subsequently validate/rewrite each affected lock. This script is a
source-preserving seed, never a successful resolution receipt.
"""
from pathlib import Path
import json
import subprocess
import tomllib
import tomli_w

BASE = Path(r'C:\Users\mark_\Code\repos')
HERE = BASE / 'mere/support/family-promotion'
mapping = json.loads((HERE / 'package-map.json').read_text())
revisions = json.loads((HERE / 'supplier-revisions.json').read_text())
ledger = json.loads((HERE / 'consumer-cutover.json').read_text())
roots = {BASE / Path(row['path']).relative_to(BASE).parts[0] for row in ledger['changes']}
roots.discard(BASE / 'isocosm')  # Its unpublished main commit is deliberately isolated.
roots.add(Path(r'C:\Users\mark_\Code\worktrees\isocosm-family-promotion'))
report = []
for root in sorted(roots):
    files = subprocess.check_output(['git', 'ls-files', '--', 'Cargo.lock', '**/Cargo.lock'], cwd=root, text=True).splitlines()
    for rel in files:
        path = root / rel
        if root == BASE / 'mere' and rel == 'Cargo.lock':
            continue  # The independent running main-workspace gate owns this file.
        if any(part in rel.split('/') for part in ('support', 'receipts', 'archive_docs', 'fixtures', 'vendor')):
            continue
        manifest = path.with_name('Cargo.toml')
        if not manifest.exists() or not path.exists():
            continue
        original = path.read_text(encoding='utf-8-sig')
        data = tomllib.loads(original)
        changed = []
        for package in data.get('package', []):
            owner = mapping.get(package['name'])
            if owner is None or package['version'] != owner[3]:
                continue
            family = owner[0]
            source = f'git+https://github.com/merely-made/{family}.git?rev={revisions[family]}#{revisions[family]}'
            if package.get('source') == source:
                continue
            package['source'] = source
            package.pop('checksum', None)
            changed.append(package['name'])
        if changed:
            key = root.name + '-' + rel.replace('/', '-')
            backup = HERE / 'lock-before' / key
            if backup.exists():
                raise RuntimeError('Lock preservation already exists: ' + str(backup))
            backup.parent.mkdir(exist_ok=True)
            backup.write_bytes(path.read_bytes())
            path.write_text('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n'+tomli_w.dumps(data), encoding='utf-8', newline='\n')
            report.append({'root': str(root), 'lock': rel, 'seeded_packages': changed, 'requires_cargo_validation': True})
(HERE / 'consumer-lock-seeds.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
print(json.dumps(report, indent=2))
