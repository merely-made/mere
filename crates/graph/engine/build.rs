//! Compiles the core pack (`src/profile/core/pack.toml`) to its canonical
//! CBOR and emits the engine's id constants (declared-lens D8, D13), and the
//! alignment pack (`src/profile/alignment/pack.toml`, D35) beside it. The
//! core pack's prefixes, which its canonical form drops, are emitted too, for
//! `profile::core::expand` (D41). A term's
//! dense id is its position in the core pack's canonical term order, which is
//! the order `profile::intern` assigns, since the core pack loads first.

use std::fmt::Write as _;
use std::path::PathBuf;

const CORE: &str = "src/profile/core/pack.toml";
const ALIGNMENT: &str = "src/profile/alignment/pack.toml";
/// Every core term lives under this namespace; its constant is named for the rest.
const NS: &str = "https://mere.computer/ns/";

/// The authored `[prefixes]` table as a Rust constant. The table's lines are
/// `name = "namespace"`, which compile_authored has already checked (NCName
/// names, absolute IRIs).
fn prefixes(text: &str) -> String {
    let mut rows = Vec::new();
    let mut inside = false;
    for line in text.lines().map(str::trim) {
        if line.starts_with('[') {
            inside = line == "[prefixes]";
            continue;
        }
        if !inside || line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (name, value) = line
            .split_once('=')
            .unwrap_or_else(|| panic!("{CORE}: a prefix line {line:?} is not name = value"));
        let value = value.trim();
        let value = value
            .strip_prefix('"')
            .and_then(|v| v.strip_suffix('"'))
            .unwrap_or_else(|| panic!("{CORE}: prefix {name} is not a plain string"));
        rows.push(format!("    (\"{}\", \"{value}\"),", name.trim()));
    }
    assert!(!rows.is_empty(), "{CORE} declares no prefixes");
    format!(
        "// Generated by build.rs from the core pack; do not edit.\n\n/// The core pack's authored prefixes, name to namespace.\npub const PREFIXES: [(&str, &str); {}] = [\n{}\n];\n",
        rows.len(),
        rows.join("\n")
    )
}

fn main() {
    println!("cargo:rerun-if-changed={CORE}");
    println!("cargo:rerun-if-changed={ALIGNMENT}");
    let text = std::fs::read_to_string(CORE).expect("the core pack is readable");
    let (header, canonical) = eidetic::pack::compile_authored(&text)
        .unwrap_or_else(|e| panic!("{CORE} does not compile: {e}"));
    let terms = header
        .vocabulary()
        .expect("the core pack's vocabulary body reads")
        .expect("the core pack declares a vocabulary")
        .terms;
    let mut ids = String::from("// Generated by build.rs from the core pack; do not edit.\n\n");
    let mut table = String::new();
    for (i, term) in terms.iter().enumerate() {
        let local = term
            .iri
            .strip_prefix(NS)
            .unwrap_or_else(|| panic!("core term {} is outside {NS}", term.iri));
        let name: String = local
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() {
                    c.to_ascii_uppercase()
                } else {
                    '_'
                }
            })
            .collect();
        writeln!(
            ids,
            "/// `{}`\npub const {name}: TermId = TermId({i});",
            term.iri
        )
        .unwrap();
        writeln!(table, "    (\"{}\", {name}),", term.iri).unwrap();
    }
    writeln!(
        ids,
        "\n/// Every core term's IRI and id, in id order.\npub const TERMS: [(&str, TermId); {}] = [\n{table}];",
        terms.len()
    )
    .unwrap();
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    std::fs::write(out.join("core_pack.cbor"), canonical).expect("OUT_DIR is writable");
    std::fs::write(out.join("core_ids.rs"), ids).expect("OUT_DIR is writable");
    std::fs::write(out.join("core_prefixes.rs"), prefixes(&text)).expect("OUT_DIR is writable");
    let text = std::fs::read_to_string(ALIGNMENT).expect("the alignment pack is readable");
    let (_, alignment) = eidetic::pack::compile_authored(&text)
        .unwrap_or_else(|e| panic!("{ALIGNMENT} does not compile: {e}"));
    std::fs::write(out.join("alignment_pack.cbor"), alignment).expect("OUT_DIR is writable");
}
